#!/usr/bin/env node
/* d12-dual-bridge-audit.mjs — fail-closed parity gate for the two real D12
   execution lanes. Track 1 is the controlled native sidecar; Track 2 is the
   freestanding wasm32 adapter embedded by site/assets/d12-wasm-runtime.js.
   Both lanes run the same upstream experimental path and must emit the exact
   same canonical D12R bytes for golden, refusal, and hostile-input vectors.

   Modes:
     node tools/d12-dual-bridge-audit.mjs           # execute checks
     node tools/d12-dual-bridge-audit.mjs --verify  # execute + byte-compare artifacts
     node tools/d12-dual-bridge-audit.mjs --emit    # execute + write artifacts */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { execute as nativeExecute } from "../security/d12-native-bridge.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const SDK_ROOT = path.resolve(ROOT, "..", "D12", "d12-wasmrt-sdk");
const SDK_LABEL = "../D12/d12-wasmrt-sdk";
const FIXTURE = path.join(SDK_ROOT, "tests", "fixtures", "wide_sample.wasm");
const OUT_DIR = path.join(ROOT, "security", "out", "d12-dual");
const NATIVE_BIN = path.join(OUT_DIR, "d12-native-adapter");
const WASM_BIN = path.join(OUT_DIR, "d12-wasm-sandbox.wasm");
const RUNTIME_JS = path.join(ROOT, "site", "assets", "d12-wasm-runtime.js");
const EVIDENCE = path.join(ROOT, "site", "assets", "d12-dual-bridge-audit.json");
const EMIT = process.argv.includes("--emit");
const VERIFY = process.argv.includes("--verify");

const EXPECTED_FIXTURE_SHA =
  "d207446ed7260de487dd442d8a2c7c3ff27052d8177925ffce51389acbf84dfa";
const REPORT_BYTES = 704;
const REQUIRED_EXPORTS = [
  "d12_exec", "d12_input_capacity", "d12_input_ptr",
  "d12_report_len", "d12_report_ptr", "memory",
];

const sha256 = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const sha256File = file => sha256(fs.readFileSync(file));

function run(command, args, options = {}) {
  const started = process.hrtime.bigint();
  const result = spawnSync(command, args, {
    cwd: options.cwd || ROOT,
    encoding: "utf8",
    timeout: options.timeout ?? 300_000,
    maxBuffer: 16 * 1024 * 1024,
    env: { ...process.env, ...(options.env || {}) },
  });
  return {
    status: result.status,
    signal: result.signal || null,
    stdout: result.stdout || "",
    stderr: result.stderr || "",
    duration_ms: Number((process.hrtime.bigint() - started) / 1_000_000n),
    error: result.error ? String(result.error.message || result.error) : null,
  };
}

function runtimeSource(wasmBytes, fixtureBytes) {
  const wasmB64 = Buffer.from(wasmBytes).toString("base64");
  const fixtureB64 = Buffer.from(fixtureBytes).toString("base64");
  return `/* d12-wasm-runtime.js — generated by tools/d12-dual-bridge-audit.mjs.
   This embeds the freestanding wasm32 D12 experimental adapter. It executes
   only d12.profile/d12.code workloads; it is not a standard wasm128/wasm256
   engine and not the full upstream sdk.Runtime host. */
(function (root) {
  "use strict";
  var VERSION = "D12-WASMRT-ADAPTER-v1";
  var WASM_SHA256 = "${sha256(wasmBytes)}";
  var FIXTURE_SHA256 = "${sha256(fixtureBytes)}";
  var WASM_B64 = "${wasmB64}";
  var FIXTURE_B64 = "${fixtureB64}";
  var REPORT_BYTES = ${REPORT_BYTES};

  function b64(s) {
    var alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    var clean = s.replace(/\\s+/g, "");
    var pad = clean.endsWith("==") ? 2 : clean.endsWith("=") ? 1 : 0;
    var out = new Uint8Array((clean.length * 3 / 4) - pad);
    var bits = 0, used = 0, at = 0;
    for (var i = 0; i < clean.length; i++) {
      var v = alphabet.indexOf(clean[i]);
      if (v < 0) throw new RangeError("bad base64");
      bits = (bits << 6) | v; used += 6;
      if (used >= 8) {
        used -= 8;
        if (at < out.length) out[at++] = (bits >>> used) & 255;
      }
    }
    return out;
  }
  function bytes(v) {
    if (v instanceof Uint8Array) return v;
    if (v instanceof ArrayBuffer) return new Uint8Array(v);
    throw new RangeError("module must be u8 bytes");
  }
  function run(instance, moduleBytes, profile, fuel) {
    var x = instance.exports;
    var cap = Number(x.d12_input_capacity());
    var input = bytes(moduleBytes);
    if (input.length > cap) throw new RangeError("D12 module exceeds adapter input window");
    var memory = new Uint8Array(x.memory.buffer);
    memory.set(input, Number(x.d12_input_ptr()));
    var status = Number(x.d12_exec(input.length, Number(profile), BigInt(fuel)));
    var ptr = Number(x.d12_report_ptr());
    var len = Number(x.d12_report_len());
    if (len !== REPORT_BYTES) throw new Error("D12R report length drifted");
    return { status: status, report: new Uint8Array(x.memory.buffer.slice(ptr, ptr + len)) };
  }
  root.D12_WASM_RUNTIME = {
    version: VERSION,
    wasmSha256: WASM_SHA256,
    fixtureSha256: FIXTURE_SHA256,
    boundary: "experimental d12.profile/d12.code adapter only; no standard wasm128/wasm256 claim",
    fixture: function () { return b64(FIXTURE_B64); },
    instantiate: async function () {
      var compiled = await WebAssembly.instantiate(b64(WASM_B64), {});
      return compiled.instance;
    },
    execute: async function (moduleBytes, profile, fuel) {
      return run(await this.instantiate(), moduleBytes, profile === undefined ? 128 : profile,
        fuel === undefined ? 1024n : fuel);
    },
    executeOn: run
  };
})(globalThis);
`;
}

function wasmExecute(instance, input, profile, fuel) {
  const x = instance.exports;
  const memory = new Uint8Array(x.memory.buffer);
  memory.set(input, Number(x.d12_input_ptr()));
  const status = Number(x.d12_exec(input.length, Number(profile), BigInt(fuel)));
  const ptr = Number(x.d12_report_ptr());
  const len = Number(x.d12_report_len());
  const report = Buffer.from(new Uint8Array(x.memory.buffer.slice(ptr, ptr + len)));
  return { status, report };
}

async function audit() {
  const checks = [];
  const failures = [];
  const commands = [];
  const check = (id, ok, detail = "") => {
    checks.push({ id, status: ok ? "PASS" : "FAIL" });
    if (!ok) failures.push(`${id}: ${detail || "failed"}`);
    return ok;
  };
  const command = (id, display, r, detail = "") => {
    commands.push({ id, command: display, status: r.status === 0 ? "PASS" : "FAIL" });
    return check(`command:${id}`, r.status === 0,
      detail || `exit ${r.status ?? "null"}${r.signal ? ` signal=${r.signal}` : ""}`);
  };

  check("sdk-root", fs.existsSync(SDK_ROOT) && fs.statSync(SDK_ROOT).isDirectory(), SDK_LABEL);
  const sources = [
    "security/d12_dual_core.zig",
    "security/d12_native_adapter.zig",
    "security/d12_wasm_adapter.zig",
    "security/d12-native-bridge.mjs",
  ];
  check("adapter-sources", sources.every(rel => fs.existsSync(path.join(ROOT, rel))),
    sources.join(", "));
  if (failures.length) return { checks, failures, report: null, runtimeSource: null };

  const fixture = fs.readFileSync(FIXTURE);
  const fixtureSha = sha256(fixture);
  check("wide-fixture-hash", fixtureSha === EXPECTED_FIXTURE_SHA,
    `tests/fixtures/wide_sample.wasm sha256=${fixtureSha}`);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const zigSources = sources.filter(rel => rel.endsWith(".zig")).map(rel => path.join(ROOT, rel));
  command("zig-fmt", `zig fmt --check (${zigSources.length} adapter files)`,
    run("zig", ["fmt", "--check", ...zigSources], { timeout: 120_000 }));
  const coreTest = run("zig", [
    "test", "--dep", "d12",
    "-Mmain=security/d12_dual_core.zig",
    `-Md12=${path.join(SDK_ROOT, "src", "lib.zig")}`,
  ], { timeout: 300_000 });
  command("dual-core-test", "zig test security/d12_dual_core.zig (module d12)", coreTest,
    (coreTest.stdout + coreTest.stderr).includes("All 1 tests passed.") ?
      "canonical report deterministic test passed" : "test marker missing");
  if (!((coreTest.stdout + coreTest.stderr).includes("All 1 tests passed."))) coreTest.status = 1;

  command("native-build", "zig build-exe d12_native_adapter.zig (native)", run("zig", [
    "build-exe", "-O", "ReleaseSafe", "--dep", "d12",
    "-Mmain=security/d12_native_adapter.zig",
    `-Md12=${path.join(SDK_ROOT, "src", "lib.zig")}`,
    `-femit-bin=${NATIVE_BIN}`,
  ], { timeout: 300_000 }));
  command("wasm-build", "zig build-exe d12_wasm_adapter.zig (wasm32-freestanding)", run("zig", [
    "build-exe", "-target", "wasm32-freestanding", "-fno-entry", "-rdynamic",
    "-O", "ReleaseSmall", "--dep", "d12",
    "-Mmain=security/d12_wasm_adapter.zig",
    `-Md12=${path.join(SDK_ROOT, "src", "lib.zig")}`,
    `-femit-bin=${WASM_BIN}`,
  ], { timeout: 300_000 }));
  check("native-artifact", fs.existsSync(NATIVE_BIN), "security/out/d12-dual/d12-native-adapter");
  check("wasm-artifact", fs.existsSync(WASM_BIN), "security/out/d12-dual/d12-wasm-sandbox.wasm");
  if (failures.length) return { checks, failures, report: null, runtimeSource: null };

  const wasm = fs.readFileSync(WASM_BIN);
  check("wasm-binary-header", wasm.length > 8 &&
    wasm[0] === 0x00 && wasm[1] === 0x61 && wasm[2] === 0x73 && wasm[3] === 0x6d &&
    wasm[4] === 0x01 && wasm[5] === 0x00 && wasm[6] === 0x00 && wasm[7] === 0x00,
    `${wasm.length} bytes`);
  const compiled = await WebAssembly.compile(wasm);
  const imports = WebAssembly.Module.imports(compiled);
  const exportsList = WebAssembly.Module.exports(compiled).map(e => e.name).sort();
  check("wasm-zero-imports", imports.length === 0,
    `${imports.length} host imports`);
  check("wasm-export-surface", JSON.stringify(exportsList) === JSON.stringify([...REQUIRED_EXPORTS].sort()),
    exportsList.join(","));
  const { instance } = await WebAssembly.instantiate(wasm, {});
  check("wasm-input-window", Number(instance.exports.d12_input_capacity()) === 1 << 20,
    `${Number(instance.exports.d12_input_capacity())} bytes`);
  check("wasm-report-window", Number(instance.exports.d12_report_len()) === REPORT_BYTES,
    `${REPORT_BYTES} bytes`);

  const runtime = runtimeSource(wasm, fixture);
  check("runtime-source-boundary",
    runtime.includes("D12_WASM_RUNTIME") && runtime.includes("WebAssembly.instantiate") &&
    !runtime.includes("fetch(") && !runtime.includes("XMLHttpRequest") &&
    !runtime.includes("localStorage") && !runtime.includes("Buffer."),
    "embedded artifact + browser-safe API + no fetch/DOM storage/Buffer dependency");
  const runtimeCheckPath = path.join(OUT_DIR, "d12-wasm-runtime.generated.js");
  fs.writeFileSync(runtimeCheckPath, runtime);
  const runtimeSyntax = run(process.execPath, ["--check", runtimeCheckPath], { timeout: 120_000 });
  command("runtime-js-syntax", "node --check generated d12-wasm-runtime.js", runtimeSyntax);

  const vectors = [];
  const mutated = Buffer.from(fixture);
  mutated[mutated.length - 1] ^= 0x01;
  const mutatedPath = path.join(OUT_DIR, "mutated.wasm");
  fs.writeFileSync(mutatedPath, mutated);
  const specs = [
    { id: "golden-128", modulePath: FIXTURE, bytes: fixture, profile: 128, fuel: 1024, expected: 0 },
    { id: "fuel-bound", modulePath: FIXTURE, bytes: fixture, profile: 128, fuel: 1, expected: 5 },
    { id: "bad-profile", modulePath: FIXTURE, bytes: fixture, profile: 64, fuel: 1024, expected: 3 },
    { id: "mutated-module", modulePath: mutatedPath, bytes: mutated, profile: 128, fuel: 1024, expected: 4 },
  ];
  for (const spec of specs) {
    let native = null, wasmLane = null, errorText = "";
    try {
      native = nativeExecute({ adapterPath: NATIVE_BIN, modulePath: spec.modulePath,
        profile: spec.profile, fuel: spec.fuel });
      wasmLane = wasmExecute(instance, spec.bytes, spec.profile, spec.fuel);
    } catch (e) { errorText = e.message || String(e); }
    const parity = native && wasmLane && native.report.equals(wasmLane.report);
    check(`lane-parity:${spec.id}`, parity,
      parity ? `status=${native.status} report_sha256=${sha256(native.report)}` : errorText);
    check(`lane-status:${spec.id}`, native && wasmLane &&
      native.status === wasmLane.status && native.status === spec.expected,
      native && wasmLane ? `${native.status}/${wasmLane.status} expected ${spec.expected}` : "lane failed");
    vectors.push({
      id: spec.id,
      profile: spec.profile,
      fuel: spec.fuel,
      status: native ? native.status : null,
      native_report_sha256: native ? sha256(native.report) : null,
      wasm_report_sha256: wasmLane ? sha256(wasmLane.report) : null,
      byte_exact: !!parity,
    });
  }

  const sidecar = run(process.execPath, [
    path.join(ROOT, "security", "d12-native-bridge.mjs"),
    "--module", FIXTURE, "--profile", "128", "--fuel", "1024",
    "--adapter", NATIVE_BIN,
  ], { timeout: 120_000 });
  command("native-sidecar-cli", "node security/d12-native-bridge.mjs --module <wide_sample> --profile 128 --fuel 1024",
    sidecar, (sidecar.stdout.match(/^report_sha256=([0-9a-f]{64})$/m) || [])[1] ===
      (vectors[0]?.native_report_sha256 || "") ? "canonical report hash held" : "report hash marker missing");

  const report = {
    schema: "SPEC007-D12-DUAL-BRIDGE-AUDIT-v1",
    boundary: {
      sdk_root: SDK_LABEL,
      integration: "upstream sibling linked at build time; source is not vendored into Spec-007",
      native_track: "security/d12_native_adapter.zig behind security/d12-native-bridge.mjs process IPC",
      wasm_track: "security/d12_wasm_adapter.zig compiled wasm32-freestanding and embedded by site/assets/d12-wasm-runtime.js",
      execution_scope: "experimental d12.profile/d12.code workloads only",
      standard_wasm128_wasm256_claim: false,
      full_browser_sdk_runtime: false,
      fano_wire_scope: "FRB1 remains an envelope/ownership lane; these vectors exercise D12 execution directly",
    },
    provenance: {
      release: "experimental-width-feasibility-2026-10-16",
      wide_fixture_sha256: fixtureSha,
      adapter_source_sha256: Object.fromEntries(sources.map(rel => [
        rel, sha256File(path.join(ROOT, rel)),
      ])),
      native_adapter_sha256: sha256File(NATIVE_BIN),
      wasm_adapter_sha256: sha256File(WASM_BIN),
      runtime_js_sha256: sha256(runtime),
      wasm_import_count: imports.length,
      wasm_exports: exportsList,
      input_window_bytes: Number(instance.exports.d12_input_capacity()),
      report_bytes: REPORT_BYTES,
    },
    verification: {
      checks: checks.map(c => ({ id: c.id, status: c.status })),
      commands,
      lane_vectors: vectors,
      runtime_artifact: "site/assets/d12-wasm-runtime.js",
    },
  };
  return { checks, failures, report, runtimeSource: runtime };
}

const { checks, failures, report, runtimeSource: generatedRuntime } = await audit();
const pretty = report ? JSON.stringify(report, null, 2) + "\n" : null;
const green = failures.length === 0 && report && checks.every(c => c.status === "PASS");

for (const c of checks)
  console.log(`  [${c.status}] ${c.id}`);

if (!green) {
  console.error(`d12-dual-bridge-audit: FAIL — ${failures.join("; ")}`);
  process.exit(1);
}

if (EMIT) {
  fs.mkdirSync(path.dirname(RUNTIME_JS), { recursive: true });
  fs.writeFileSync(RUNTIME_JS, generatedRuntime);
  fs.writeFileSync(EVIDENCE, pretty);
  console.log(`d12-dual-bridge-audit: ${checks.length} checks green → site/assets/d12-wasm-runtime.js + d12-dual-bridge-audit.json`);
} else if (VERIFY) {
  const sameRuntime = fs.existsSync(RUNTIME_JS) && fs.readFileSync(RUNTIME_JS, "utf8") === generatedRuntime;
  const sameEvidence = fs.existsSync(EVIDENCE) && fs.readFileSync(EVIDENCE, "utf8") === pretty;
  if (!sameRuntime || !sameEvidence) {
    console.error("d12-dual-bridge-audit: artifact drift — run --emit after adapter refresh");
    process.exit(1);
  }
  console.log(`d12-dual-bridge-audit: ${checks.length} checks green; runtime and evidence byte-exact`);
} else {
  console.log(`d12-dual-bridge-audit: ${checks.length} checks green; --emit to write artifacts`);
}
