#!/usr/bin/env node
// archive-projection.mjs — project the ~/.archives corpus into a sanitized
// public snapshot (site/assets/archive-manifest.json). The desk's
// continuity pane reads this; the raw archive stays off-site.
//
// Sanitization contract: basenames only — no absolute paths, no drawer
// names, no key material. Sealed = SHA256SUMS (dirs) or .sha256 sidecar
// (tarballs); unsealed entries are listed honestly, not hidden.
//
//   node tools/archive-projection.mjs           # dry-run
//   node tools/archive-projection.mjs --emit    # write the snapshot
import path from "node:path";
import fs from "node:fs";
import os from "node:os";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const ARCHIVES = process.env.FANO_ARCHIVES ?? path.join(os.homedir(), ".archives");
const OUT = path.join(ROOT, "site", "assets", "archive-manifest.json");

const entries = [];
if (fs.existsSync(ARCHIVES)) {
  for (const name of fs.readdirSync(ARCHIVES).sort()) {
    const p = path.join(ARCHIVES, name);
    const st = fs.statSync(p);
    if (st.isDirectory()) {
      const sealed = fs.existsSync(path.join(p, "SHA256SUMS"));
      const files = fs.readdirSync(p).filter((f) => f !== "SHA256SUMS").length;
      entries.push({ name, kind: "dir", sealed, files });
    } else if (/\.(tar\.gz|tgz|tar|zip|gz)$/.test(name) || name.endsWith(".sha256")) {
      /* sidecars belong to their tarballs — not listed twice */
      if (name.endsWith(".sha256")) continue;
      entries.push({ name, kind: "bundle",
        sealed: fs.existsSync(p + ".sha256") });
    } else {
      entries.push({ name, kind: "file", sealed: false });
    }
  }
}

const manifest = {
  spec: "ARCHIVEMANIFESTv1",
  generated: new Date().toISOString(),
  snapshot: true,
  note: "basenames + seals only — a labeled snapshot of the archive corpus, regenerated by tools/archive-projection.mjs --emit",
  archive_count: entries.length,
  sealed_count: entries.filter((e) => e.sealed).length,
  archives: entries,
};

if (!process.argv.includes("--emit")) {
  console.log(JSON.stringify(manifest, null, 2));
  console.error(`dry-run — ${entries.length} archives (${manifest.sealed_count} sealed) · --emit to publish the snapshot`);
  process.exit(0);
}
fs.writeFileSync(OUT, JSON.stringify(manifest, null, 2));
console.log(`archive projection → ${OUT} (${entries.length} archives, ${manifest.sealed_count} sealed)`);
